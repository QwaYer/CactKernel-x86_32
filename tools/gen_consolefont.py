def rev8(b):
    b = ((b & 0xF0) >> 4) | ((b & 0x0F) << 4)
    b = ((b & 0xCC) >> 2) | ((b & 0x33) << 2)
    b = ((b & 0xAA) >> 1) | ((b & 0x55) << 1)
    return b


def main(argv):
    out_path = argv[1] if len(argv) > 1 else "consolefont.psf"

    width, height = 8, 8
    num_glyphs = 256
    bytes_per_glyph = height * ((width + 7) // 8)

    header = struct.pack(
        "<4s7I",
        b"\x72\xB5\x4A\x86",  # PSF2 magic
        0,                    # version
        32,                   # header size (bitmap offset)
        1 if HAS_UNICODE else 0,
        num_glyphs,
        bytes_per_glyph,
        height,
        width,
    )

    bitmaps = bytearray()
    for g in range(num_glyphs):
        src = FONT8X8[g] if g < len(FONT8X8) else None
        for row in range(height):
            bitmaps.append(rev8(src[row]) if src else 0)

    uni = bytearray()
    for g in range(num_glyphs):
        uni += bytes((g,)) + b"\xFF" if g < len(FONT8X8) else b"\xFF"

    with open(out_path, "wb") as f:
        f.write(header)
        f.write(bitmaps)
        if HAS_UNICODE:
            f.write(uni)

    total = len(header) + len(bitmaps) + len(uni)
    print(f"wrote {out_path}: {total} bytes, {num_glyphs} glyphs {width}x{height}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
